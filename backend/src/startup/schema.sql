CREATE TABLE IF NOT EXISTS schema_migrations (
  version VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS countries (name VARCHAR(255) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS room_types (name VARCHAR(100) PRIMARY KEY);
CREATE TABLE IF NOT EXISTS rooms (
  room_number VARCHAR(10) PRIMARY KEY,
  room_type VARCHAR(100) NOT NULL,
  synthetic BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (room_type) REFERENCES room_types(name)
);
CREATE TABLE IF NOT EXISTS seasonal_rates (
  room_type VARCHAR(100) NOT NULL, season VARCHAR(4) CHECK (season IN ('low','mid','high')) NOT NULL,
  nightly_price DECIMAL(18,2) NOT NULL,
  PRIMARY KEY (room_type,season), FOREIGN KEY (room_type) REFERENCES room_types(name)
);
CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY,
  holder_first_name VARCHAR(255) NOT NULL, holder_last_name VARCHAR(255) NOT NULL,
  holder_country VARCHAR(255) NOT NULL, guest_count BIGINT NULL CHECK (guest_count BETWEEN 1 AND 4294967295),
  arrival DATE NOT NULL, departure DATE NOT NULL, nights BIGINT NOT NULL,
  status VARCHAR(9) CHECK (status IN ('active','cancelled')) NOT NULL DEFAULT 'active', version BIGINT NOT NULL DEFAULT 1,
  total_price DECIMAL(18,2) NOT NULL,
  synthetic_dates BOOLEAN NOT NULL DEFAULT FALSE, synthetic_room_assignment BOOLEAN NOT NULL DEFAULT FALSE,
  source_id VARCHAR(255) NULL,
  FOREIGN KEY (holder_country) REFERENCES countries(name),
  CHECK (departure > arrival), CHECK (nights > 0)
);
CREATE TABLE IF NOT EXISTS booking_guests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 4294967295) PRIMARY KEY, booking_id BIGINT NOT NULL,
  first_name VARCHAR(255) NOT NULL, last_name VARCHAR(255) NOT NULL,
  FOREIGN KEY (booking_id) REFERENCES bookings(id)
);
CREATE TABLE IF NOT EXISTS booking_rooms (
  booking_id BIGINT NOT NULL, room_number VARCHAR(10) NOT NULL, room_total DECIMAL(18,2) NOT NULL,
  PRIMARY KEY (booking_id,room_number),
  FOREIGN KEY (booking_id) REFERENCES bookings(id), FOREIGN KEY (room_number) REFERENCES rooms(room_number)
);
CREATE TABLE IF NOT EXISTS room_nights (
  booking_id BIGINT NOT NULL, room_number VARCHAR(10) NOT NULL, night_date DATE NOT NULL,
  season VARCHAR(4) CHECK (season IN ('low','mid','high')) NOT NULL, exact_charge DECIMAL(18,2) NOT NULL,
  PRIMARY KEY (booking_id,room_number,night_date),
  FOREIGN KEY (booking_id,room_number) REFERENCES booking_rooms(booking_id,room_number)
);

CREATE INDEX IF NOT EXISTS allocation_room ON booking_rooms (room_number,booking_id);
