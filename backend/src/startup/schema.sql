CREATE TABLE IF NOT EXISTS satisfaction_responses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id BIGINT NOT NULL REFERENCES bookings(id),
  room_number VARCHAR(10) NOT NULL REFERENCES rooms(room_number),
  rating NUMERIC NOT NULL CHECK (rating >= 1 AND rating <= 5),
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS satisfaction_room ON satisfaction_responses(room_number, booking_id);

